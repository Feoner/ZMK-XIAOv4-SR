#!/usr/bin/env python3
"""Convert an animated GIF into 1-bit LVGL 8 image descriptors for the vendored
nice_oled shield (config/boards/shields/nice_oled).

Usage:
    python3 tools/gif_to_nice_oled.py path/to/catbus.gif \
        config/boards/shields/nice_oled/assets/catbus.c

Produces:
  - catbus_0 .. catbus_N  : animation frames, FRAME_W x 68, drawn by the
                            peripheral animation widget (X offset 36, so the
                            usable width is 160 - 36 = 124 px).
  - catbus_sleep          : one full-screen 160 x 68 still used as sleep art.

Images are stored in raw display orientation (160 x 68 landscape). The nice!view
is mounted portrait, so the art shows up rotated: the bus runs up the screen.

Rendering: outline of the silhouette plus dark/mid-tone details (stripes,
windows, eye) become foreground pixels; everything else is background.

Requires Pillow (pip install pillow).
"""
import sys

from PIL import Image, ImageChops, ImageFilter, ImageSequence

PREFIX = "catbus"
FRAME_W, FRAME_H = 124, 68  # animation slot
SLEEP_W, SLEEP_H = 160, 68  # full screen
ART_H_FRAME = 58            # catbus height inside an animation frame
ART_H_SLEEP = 68            # catbus height inside the sleep image
DETAIL_THRESHOLD = 175      # luminance below this inside the body = ink


def load_frames(path):
    im = Image.open(path)
    frames = [f.convert("RGBA") for f in ImageSequence.Iterator(im)]
    durations = [f.info.get("duration", 100) for f in ImageSequence.Iterator(Image.open(path))]
    # crop to the union bounding box so every frame keeps the same framing
    boxes = [f.getbbox() for f in frames]
    x0 = min(b[0] for b in boxes)
    y0 = min(b[1] for b in boxes)
    x1 = max(b[2] for b in boxes)
    y1 = max(b[3] for b in boxes)
    return [f.crop((x0, y0, x1, y1)) for f in frames], durations


def to_ink(frame, w, h):
    """Return an 'L' image where 255 = foreground pixel."""
    alpha = frame.getchannel("A").resize((w, h), Image.BOX).point(lambda v: 255 if v >= 128 else 0)
    flat = Image.new("RGBA", frame.size, (255, 255, 255, 255))
    flat.alpha_composite(frame)
    lum = flat.convert("L").resize((w, h), Image.BOX)
    detail = ImageChops.multiply(lum.point(lambda v: 255 if v < DETAIL_THRESHOLD else 0), alpha)
    edge = alpha.filter(ImageFilter.FIND_EDGES).point(lambda v: 255 if v else 0)
    return ImageChops.lighter(edge, detail)


def place(ink_art, canvas_w, canvas_h):
    canvas = Image.new("L", (canvas_w, canvas_h), 0)
    canvas.paste(ink_art, ((canvas_w - ink_art.width) // 2, (canvas_h - ink_art.height) // 2))
    return canvas


def scaled(frame, target_h, max_w):
    w = round(frame.width * target_h / frame.height)
    h = target_h
    if w > max_w:
        h = round(h * max_w / w)
        w = max_w
    return to_ink(frame, w, h)


def pack(img):
    w, h = img.size
    stride = (w + 7) // 8
    px = img.load()
    out = bytearray(stride * h)
    for y in range(h):
        for x in range(w):
            if px[x, y]:
                out[y * stride + x // 8] |= 0x80 >> (x % 8)
    return bytes(out)


def emit(name, img):
    data = pack(img)
    lines = []
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
    w, h = img.size
    return f"""
#ifndef LV_ATTRIBUTE_IMG_{name.upper()}
#define LV_ATTRIBUTE_IMG_{name.upper()}
#endif

static const LV_ATTRIBUTE_MEM_ALIGN LV_ATTRIBUTE_IMG_{name.upper()} uint8_t {name}_map[] = {{
#if CONFIG_NICE_OLED_WIDGET_INVERTED
    0x00, 0x00, 0x00, 0xff, 0xff, 0xff, 0xff, 0xff, /* idx0 black, idx1 white */
#else
    0xff, 0xff, 0xff, 0xff, 0x00, 0x00, 0x00, 0xff, /* idx0 white, idx1 black */
#endif
{chr(10).join(lines)}
}};

const lv_img_dsc_t {name} = {{
    .header.cf = LV_IMG_CF_INDEXED_1BIT,
    .header.always_zero = 0,
    .header.reserved = 0,
    .header.w = {w},
    .header.h = {h},
    .data_size = {8 + len(data)},
    .data = {name}_map,
}};
"""


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    gif_path, out_path = sys.argv[1], sys.argv[2]
    frames, durations = load_frames(gif_path)

    parts = [
        "/*\n"
        f" * Generated by tools/gif_to_nice_oled.py from {gif_path.split('/')[-1]}\n"
        f" * {len(frames)} animation frame(s) ({FRAME_W}x{FRAME_H}) + sleep art ({SLEEP_W}x{SLEEP_H}).\n"
        f" * Source frame durations (ms): {durations}\n"
        " * Do not edit by hand; re-run the script instead.\n"
        " */\n"
        "#include <lvgl.h>\n\n"
        "#ifndef LV_ATTRIBUTE_MEM_ALIGN\n#define LV_ATTRIBUTE_MEM_ALIGN\n#endif\n"
    ]
    for i, f in enumerate(frames):
        parts.append(emit(f"{PREFIX}_{i}", place(scaled(f, ART_H_FRAME, FRAME_W), FRAME_W, FRAME_H)))
    parts.append(emit(f"{PREFIX}_sleep", place(scaled(frames[0], ART_H_SLEEP, SLEEP_W), SLEEP_W, SLEEP_H)))

    with open(out_path, "w") as fh:
        fh.write("".join(parts))
    print(f"wrote {out_path}: {len(frames)} frames, total loop {sum(durations)} ms")


if __name__ == "__main__":
    main()
